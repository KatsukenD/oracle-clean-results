function getColumns(
  rows: Array<Record<string, unknown>>
): string[] {

  const columns: string[] =
    [];

  const seen =
    new Set<string>();

  for (const row of rows) {

    for (
      const key of Object.keys(row)
    ) {

      if (!seen.has(key)) {

        seen.add(key);
        columns.push(key);

      }

    }

  }

  return columns;
}

function formatCell(
  value: unknown
): string {

  if (
    value === null ||
    value === undefined
  ) {
    return '';
  }

  if (
    value instanceof Date
  ) {
    return escapeHtml(
      value.toISOString()
    );
  }

  if (
    typeof value === 'object'
  ) {

    try {

      return escapeHtml(
        JSON.stringify(value)
      );

    } catch {

      return escapeHtml(
        String(value)
      );

    }

  }

  return escapeHtml(
    String(value)
  );
}

function escapeHtml(
  value: string
): string {

  return value
    .replaceAll(
      '&',
      '&amp;'
    )
    .replaceAll(
      '<',
      '&lt;'
    )
    .replaceAll(
      '>',
      '&gt;'
    )
    .replaceAll(
      '"',
      '&quot;'
    )
    .replaceAll(
      "'",
      '&#039;'
    );
}